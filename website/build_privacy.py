"""Generate website/public/privacy.html from the app's bundled PRIVACY.md.

The macOS app shows ios/MedicalFactChecker/PRIVACY.md in its Privacy window,
and the stores link to https://medfactcheck.org/privacy; generating one from
the other keeps the two copies identical.

Usage:
    python website/build_privacy.py          # write privacy.html
    python website/build_privacy.py --check  # exit 1 if privacy.html is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import markdown

REPO_ROOT = Path(__file__).resolve().parent.parent
SOURCE = REPO_ROOT / "ios" / "MedicalFactChecker" / "PRIVACY.md"
TARGET = REPO_ROOT / "website" / "public" / "privacy.html"

PAGE = """<!doctype html>
<!-- Generated by website/build_privacy.py from ios/MedicalFactChecker/PRIVACY.md. Edit that file, not this one. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>Privacy Policy | Medical Fact Checker</title>
<meta name="description" content="How Medical Fact Checker for iPhone, iPad, Mac and Android handles your data: no servers, no accounts, no analytics.">
<link rel="icon" href="/icon.svg" type="image/svg+xml">
<link rel="canonical" href="https://medfactcheck.org/privacy">
<link rel="stylesheet" href="/styles.css">
</head>
<body>
<div class="wrap">
  <header class="site-head">
    <a class="brand" href="/"><img src="/icon.svg" alt="" width="32" height="32">Medical Fact Checker</a>
    <nav aria-label="Site">
      <a href="/#how">How it works</a>
      <a href="/#support">Support</a>
      <a href="/privacy" aria-current="page">Privacy</a>
    </nav>
  </header>
  <main class="policy prose">
{body}
  </main>
  <footer class="site-foot">
    <p>&copy; 2024&ndash;2026 Dr Horst Herb. <a href="/">Medical Fact Checker</a>. <a href="https://github.com/hherb/bmlibrarian_lite">Source code</a>.</p>
  </footer>
</div>
</body>
</html>
"""


def render(source_text: str) -> str:
    """Render the policy's Markdown as the full privacy page.

    Args:
        source_text: The contents of PRIVACY.md.

    Returns:
        The complete HTML document for privacy.html.
    """
    body = markdown.markdown(source_text, extensions=["tables"])
    # Wide tables scroll inside their own box so the page never scrolls sideways on a phone.
    body = body.replace("<table>", '<div class="table-scroll"><table>').replace(
        "</table>", "</table></div>"
    )
    return PAGE.format(body=body)


def main() -> int:
    """Write privacy.html, or with --check report whether it is current.

    Returns:
        The process exit code: 0 on success, 1 if --check finds it stale.
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if privacy.html is stale")
    args = parser.parse_args()

    page = render(SOURCE.read_text(encoding="utf-8"))
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != page:
            print(f"{TARGET} is stale: run python website/build_privacy.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(page, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
